#Modulos e bibliotecas
# import math siginifica que você está importando a biblioteca math, que contém funções matemáticas,
#  como raiz quadrada, seno, cosseno, etc.    


# ceil() arredonda para cima,
#  floor() arredonda para baixo,
#  trunc() remove a parte decimal, 
# pow() calcula a potência, 
# sqrt() calcula a raiz quadrada, 
# factorial() calcula o fatorial de um número.
# from () significa que você está importando apenas uma função específica de uma biblioteca,
#  por exemplo, from math import sqrt significa que você está importando apenas a função sqrt   
# diferença entre import math e from math import sqrt é que o primeiro importa toda a biblioteca math,
#  enquanto o segundo importa apenas a função sqrt.


