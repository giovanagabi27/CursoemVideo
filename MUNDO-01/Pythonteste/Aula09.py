#Manipulação de texto
frase = 'Curso em Vídeo Python'
print(frase[9]) #Mostra a letra na posição 9
print(frase[9:14]) #Mostra as letras da posição 9 até a 13
print(frase[9:21]) #Mostra as letras da posição 9 até a 20
print(frase[:6]) #Mostra as letras da posição 0 até a 5
print(frase[15:]) #Mostra as letras da posição 15 até o final

